"""
Regenerates core/resources/icons/material/ from the Material Icon Theme (Philipp Kief, MIT):

    python3 -I tools/generate-material-icons.py ~/.vscode/extensions/pkief.material-icon-theme-<version>

Copies only the SVGs the mapping references, sizes them to 16x16 so IconLoader renders them at the platform size,
and writes mapping.txt, one rule per line: `<kind> <key> <icon>` where kind is
f (file name), e (extension), d (folder name), and the same letters in upper case for the light-theme variants.
"""
import json
import pathlib
import re
import shutil
import sys

# Names the theme leaves to VS Code language ids or does not cover, for files common in JVM projects
EXTRA_FILE_NAMES = {
  "build.gradle.kts": "gradle",
  "settings.gradle.kts": "gradle",
  "gradle.properties": "gradle",
  "gradle-wrapper.properties": "gradle",
  "libs.versions.toml": "gradle",
  ".env": "tune",
  "pom.xml": "maven",
}
EXTRA_EXTENSIONS = {
  "gradle.kts": "gradle",
  "rest": "http",
}


def main(theme_dir: pathlib.Path) -> None:
  out = pathlib.Path(__file__).resolve().parent.parent / "core" / "resources" / "icons" / "material"
  manifest = json.loads((theme_dir / "dist" / "material-icons.json").read_text(encoding="utf-8"))
  definitions = manifest["iconDefinitions"]

  def svg_of(icon_id: str) -> pathlib.Path:
    return (theme_dir / "dist" / definitions[icon_id]["iconPath"]).resolve()

  rules: list[tuple[str, str, str]] = []

  def add(kind: str, table: dict, light: bool = False) -> None:
    for key, icon_id in sorted(table.items()):
      if icon_id in definitions and " " not in key:
        rules.append((kind.upper() if light else kind, key.lower(), icon_id))

  add("f", {**manifest["fileNames"], **EXTRA_FILE_NAMES})
  add("e", {**manifest["fileExtensions"], **EXTRA_EXTENSIONS})
  add("d", manifest["folderNames"])
  light = manifest.get("light", {})
  add("f", light.get("fileNames", {}), light=True)
  add("e", light.get("fileExtensions", {}), light=True)
  add("d", light.get("folderNames", {}), light=True)

  icons = {icon for _, _, icon in rules} | {manifest["file"], manifest["folder"], manifest["rootFolder"]}
  icons |= {"folder-src", "folder-test", "folder-resource", "folder-packages"}

  if out.exists():
    shutil.rmtree(out)
  out.mkdir(parents=True)
  for icon_id in sorted(icons):
    text = svg_of(icon_id).read_text(encoding="utf-8")
    text = re.sub(r"<svg\b[^>]*>", lambda m: sized(m.group(0)), text, count=1)
    if icon_id.startswith("folder") and FOLDER_BODY.search(text):
      # The emblem may stick out of the folder, so light themes get a dark emblem
      (out / f"{icon_id}_onlight.svg").write_text(glass_folder(text, EMBLEM_ON_LIGHT), encoding="utf-8")
      text = glass_folder(text, EMBLEM)
    (out / f"{icon_id}.svg").write_text(text, encoding="utf-8")
  with (out / "mapping.txt").open("w", encoding="utf-8") as f:
    f.write(f"# generated by tools/generate-material-icons.py from Material Icon Theme {theme_dir.name}\n")
    f.write(f"default {manifest['file']} {manifest['folder']} {manifest['rootFolder']}\n")
    for kind, key, icon in rules:
      f.write(f"{kind} {key} {icon}\n")
  shutil.copy(theme_dir / "LICENSE.md", out / "LICENSE.md")
  print(f"{len(icons)} icons, {len(rules)} rules -> {out}")


FOLDER_TONE = "#7D96B8"
EMBLEM = "#EEF3FA"
EMBLEM_ON_LIGHT = "#3B4D66"
FOLDER_BODY = re.compile(r'<path\b(?=[^>]*\bd="M10 4H4)[^>]*?\bfill(?:="|:)(#[0-9a-fA-F]{6})[^>]*/>')


def glass_folder(text: str, emblem_color: str) -> str:
  """
  Redraws the folder body as a tab behind a front panel with a top-down gradient and a thin highlight, the soft
  "glass" look of current macOS folders. The emblem drawn on top of the body is kept as it is.
  """
  match = FOLDER_BODY.search(text)
  if match is None:
    return text
  # One calm tone for every folder, like Finder; the white emblem tells folders apart instead of the color
  color = FOLDER_TONE
  light, dark = mix(color, "#ffffff", 0.38), mix(color, "#000000", 0.22)
  emblem = re.sub(r'(fill(?:="|:))#[0-9a-fA-F]{3,8}', rf'\g<1>{emblem_color}', text[match.end():])
  emblem = re.sub(r'(stop-color(?:="|:))#[0-9a-fA-F]{3,8}', rf'\g<1>{emblem_color}', emblem)
  text = text[:match.end()] + emblem
  body = (
    f'<defs><linearGradient id="phantom-glass" x1="0" y1="0" x2="0" y2="1">'
    f'<stop offset="0" stop-color="{light}"/><stop offset="1" stop-color="{color}"/></linearGradient></defs>'
    f'<path d="M10 4H4c-1.1 0-2 .9-2 2v12h20V8c0-1.1-.9-2-2-2h-8z" fill="{dark}"/>'
    f'<rect x="2" y="7.5" width="20" height="12.5" rx="2" fill="url(#phantom-glass)"/>'
    f'<rect x="3" y="8.1" width="18" height=".9" rx=".45" fill="#ffffff" fill-opacity=".45"/>'
  )
  return text[:match.start()] + body + text[match.end():]


def mix(color: str, other: str, amount: float) -> str:
  a = [int(color[i:i + 2], 16) for i in (1, 3, 5)]
  b = [int(other[i:i + 2], 16) for i in (1, 3, 5)]
  return "#" + "".join(f"{round(x + (y - x) * amount):02x}" for x, y in zip(a, b))


def sized(tag: str) -> str:
  tag = re.sub(r'\s(width|height)="[^"]*"', "", tag)
  return tag[:-1].rstrip("/") + ' width="16" height="16">' if not tag.endswith("/>") else tag


if __name__ == "__main__":
  main(pathlib.Path(sys.argv[1]).expanduser())
